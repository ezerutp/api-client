def svg_markup(name: str, color: str, stroke_width: float = 1.8) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
        f'stroke="{color}" stroke-width="{stroke_width}" stroke-linecap="round" stroke-linejoin="round">'
        f"{_PATHS[name]}</svg>"
    )


@lru_cache(maxsize=512)
def pixmap(name: str, color: str, size: int = 16, stroke_width: float = 1.8) -> QPixmap:
    app = QApplication.instance()
    ratio = app.devicePixelRatio() if app is not None else 1.0  # type: ignore[union-attr]
    ratio = max(ratio, 2.0)  # render at 2x minimum: crisp on HiDPI, harmless elsewhere
    image = QPixmap(int(size * ratio), int(size * ratio))
    image.fill(Qt.GlobalColor.transparent)
    renderer = QSvgRenderer(QByteArray(svg_markup(name, color, stroke_width).encode()))
    painter = QPainter(image)
    painter.setRenderHint(QPainter.RenderHint.Antialiasing)
    renderer.render(painter, QRectF(0, 0, image.width(), image.height()))
    painter.end()
    image.setDevicePixelRatio(ratio)
    return image


def icon(name: str, color: str, size: int = 16, active_color: str | None = None) -> QIcon:
    result = QIcon()
    result.addPixmap(pixmap(name, color, size), QIcon.Mode.Normal)
    result.addPixmap(pixmap(name, active_color or color, size), QIcon.Mode.Active)
    result.addPixmap(pixmap(name, color, size), QIcon.Mode.Disabled)
    return result


def icon_size(size: int = 16) -> QSize:
    return QSize(size, size)
